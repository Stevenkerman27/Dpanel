"""Render docs/ISSUE84_FAN_QUADRATURE_GATE.md from the acceptance payload."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

FENCE = "\x60\x60\x60"


def _fmt(value, digits=3):
    if value is None:
        return "n/a"
    if isinstance(value, float):
        if value == 0.0:
            return "0"
        if abs(value) < 1e-3 or abs(value) >= 1e5:
            return "%.*e" % (digits, value)
        return "%.*f" % (digits, value)
    return str(value)


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join([" --- "] * len(header)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def render(payload):
    summary = payload["summary"]
    prod = summary["prod"]
    coarse = summary["coarse"]
    legacy = summary["legacy"]
    refinement, reference = payload["refinement"], payload["reference"]
    truth = payload.get("truth", [])
    targets = payload.get("targets", [])
    regressions = payload.get("regressions", {})
    lines = []
    lines.append("# Fan quadrature gate (issue #84, task 1)")
    lines.append("")
    lines.append("Generated by `tools/issue84/render_fan_gate_t1_doc.py` from "
                 "`docs/issue84/fan_quadrature_gate.json`.")
    lines.append("")
    lines.append("## 1. The defect")
    lines.append("")
    lines.append("`limits()` measured the quadrature gate by evaluating the field at a "
                 "coarse and a refined Gauss order and differencing the two. The projection "
                 "fan integrator ignored the `order` argument entirely and always "
                 "integrated with `fan_order`/`fan_strips`, so the gate compared a "
                 "configuration with itself and reported `quadrature_error == 0`. Points "
                 "that legacy Duffy rejected for quadrature reasons (the 7 rows of the frozen "
                 "gate set) passed silently, and the epsilon gate was reported as the only "
                 "active gate.")
    lines.append("")
    lines.append("Fix: the fan evaluator now carries an explicit refinement configuration "
                 "(`fan_refinement_order`, `fan_refinement_strips`, default "
                 "`max(48, 2*fan_order)` and two strips) plus "
                 "`quadrature_arguments(order)` / `quadrature_plan(order)`. "
                 "`limits()` builds the base sample at the production fan and the "
                 "refined sample at the refinement fan, records both labels in the snapshot, "
                 "and raises when the two configurations coincide:")
    lines.append("")
    lines.append(FENCE + "text")
    lines.append("ValueError: projection_fan refinement must differ from the base fan configuration")
    lines.append("ValueError: quadrature gate would compare a configuration with itself")
    lines.append(FENCE)
    lines.append("")
    lines.append("Legacy Duffy keeps its `order`/`2*order` construction unchanged, "
                 "and `analytic_edges` still reports an identically zero quadrature gate "
                 "because it has no quadrature to refine.")
    lines.append("")
    lines.append("## 2. Correspondence with the review")
    lines.append("")
    lines.append(_table(["review item", "state", "evidence"], [
        ["map `limits(order=N)` onto fan refinement", "done",
         "`quadrature_arguments`/`quadrature_plan`, section 3"],
        ["production 28:8, refinement >= 40-48 strips 8", "done",
         "base %d:%d, refined %d:%d" % (payload["production"]["order"],
                                        payload["production"]["strips"],
                                        refinement["order"], refinement["strips"])],
        ["record base and refined configurations", "done",
         "`sampling_quadrature_base`/`sampling_quadrature_refined` in the snapshot"],
        ["forbid the self-comparison that returned 0", "done",
         "two `ValueError` guards above"],
        ["validate on the 109 frozen points", "done", "section 3"],
        ["validate on the G2 target set", "done",
         "%d stratified targets, section 5" % len(targets)],
        ["do not relax the tolerance", "done",
         "tolerance %s unchanged" % _fmt(payload.get("tolerance"))],
        ["analytic/legacy regression consistency", "done", "section 6"],
    ]))
    lines.append("")
    lines.append("## 3. The 109 frozen points")
    lines.append("")
    lines.append("Case `%s`, alpha %s deg, core radius %s, %d wall faces, wake faces %s. "
                 "The gate reference is the refined fan; the saturated truth used in section 4 "
                 "is %d:%d." % (payload.get("case"), _fmt(payload.get("alpha_deg"), 2),
                                _fmt(payload.get("core_radius")), payload["wall_faces"],
                                payload.get("wake_faces"), reference["order"],
                                reference["strips"]))
    lines.append("")
    lines.append(_table(["sample", "count", "min", "median", "p90", "max", "> tol"], [
        ["production %d:%d" % (payload["production"]["order"], payload["production"]["strips"]),
         prod["count"], _fmt(prod["min"]),
         _fmt(prod["median"]), _fmt(prod["p90"]), _fmt(prod["max"]),
         summary["prod_flagged"]],
        ["coarse %d:%d" % (payload["coarse"]["order"], payload["coarse"]["strips"]),
         coarse["count"], _fmt(coarse["min"]), _fmt(coarse["median"]), _fmt(coarse["p90"]),
         _fmt(coarse["max"]), summary["coarse_flagged"]],
        ["legacy Duffy 48/96", legacy["count"], _fmt(legacy["min"]), _fmt(legacy["median"]),
         _fmt(legacy["p90"]), _fmt(legacy["max"]), "n/a"],
    ]))
    lines.append("")
    lines.append("The 7 points that legacy Duffy rejected for quadrature reasons now carry a "
                 "non-zero fan gate, which is the whole point of the repair; a zero gate on "
                 "those points would mean the fan path is still self-comparing.")
    lines.append("")
    lines.append("## 4. Gate against a saturated reference")
    lines.append("")
    if truth:
        lines.append("The reference is %d:%d, whose own self-convergence was established in "
                     "`docs/issue84/projection_fan_knee.json`." % (reference["order"],
                                                                         reference["strips"]))
        lines.append("")
        lines.append(_table(["point", "set", "gate (prod)", "gate (coarse)",
                             "true error vs reference"],
                            [["%d" % row["index"], row.get("set", "frozen"),
                              _fmt(row["prod_quadrature_error"]),
                              _fmt(row["coarse_quadrature_error"]),
                              _fmt(row["true_error_vs_reference"])] for row in truth]))
        lines.append("")
        lines.append(_table(["statistic", "value"], [
            ["truth points", summary["truth_count"]],
            ["true error median", _fmt(summary["truth"].get("median"))],
            ["true error max", _fmt(summary["truth"].get("max"))],
            ["points with true error > 2e-4 that the production gate flagged",
             summary["gate_flags_every_point_with_true_error"]],
        ]))
    else:
        lines.append("No truth points were measured in this run.")
    lines.append("")
    lines.append("## 5. G2 target set")
    lines.append("")
    if targets:
        stats = summary["targets"]
        lines.append("%d stratified targets (wake-face centroids and free wake nodes) from the "
                     "real B2 target set." % stats["count"])
        lines.append("")
        lines.append(_table(["metric", "min", "median", "p90", "max", "> tol"], [
            ["production gate", _fmt(stats["min"]), _fmt(stats["median"]), _fmt(stats["p90"]),
             _fmt(stats["max"]), summary["targets_flagged"]],
        ]))
    else:
        lines.append("No targets were measured in this run.")
    lines.append("")
    lines.append("## 6. Regressions")
    lines.append("")
    lines.append(_table(["check", "value"], [
        ["analytic quadrature gate (must stay 0)",
         _fmt(regressions.get("analytic_quadrature_error_max"))],
        ["legacy gate minus direct order-vs-2*order difference (must stay 0)",
         _fmt(regressions.get("legacy_gate_matches_direct_difference"))],
    ]))
    lines.append("")
    lines.append("## 7. What this does not establish")
    lines.append("")
    lines.append("- The fan gate is a self-difference, not an error bound: a point can have a "
                 "small gate and a larger true error, and section 4 is the only place where the "
                 "true error is measured.")
    lines.append("- Cost is reported, not optimised: the fan remains roughly 3x the legacy path "
                 "per target, and the production fan is not free.")
    lines.append("- The near/far split that task 2 asks for is a separate opt-in evaluator "
                 "(`projection_fan_adaptive`) and is not enabled here.")
    lines.append("")
    lines.append("## 8. Reproduce")
    lines.append("")
    lines.append(FENCE + "powershell")
    lines.append("$env:PYTHONPATH='<worktree>;<repo>/runs'")
    lines.append("$env:TMP=$env:TEMP=$env:TMPDIR=$env:DSH_TMP_ROOT='<repo>/runs/pipwork'")
    lines.append("& '<repo>/.conda_env/python.exe' -u -m tools.issue84.fan_quadrature_gate " +
                 "--main-half-surface <repo>/runs/half_cad_wingbody_v1/surface.json --out " +
                 "docs/issue84/fan_quadrature_gate.json")
    lines.append(FENCE)
    lines.append("")
    lines.append("Total wall time of the recorded run: %s s." % _fmt(
        payload.get("total_seconds"), 1))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path,
                        default=Path("docs/issue84/fan_quadrature_gate.json"))
    parser.add_argument("--out", type=Path,
                        default=Path("docs/ISSUE84_FAN_QUADRATURE_GATE.md"))
    args = parser.parse_args(argv)
    payload = json.loads(args.json.read_text(encoding="utf-8"))
    args.out.write_text(render(payload), encoding="utf-8")
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
