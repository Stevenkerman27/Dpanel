"""Render docs/ISSUE84_ADAPTIVE_AREA.md from the adaptive acceptance payload."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

FENCE = "\x60\x60\x60"
BT = chr(96)


def _fmt(value, digits=3):
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, float):
        if value == 0.0:
            return "0"
        if abs(value) < 1e-3 or abs(value) >= 1e5:
            return "%.*e" % (digits, value)
        return "%.*f" % (digits, value)
    return str(value)


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join([" --- "] * len(header)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def render(payload):
    summary = payload["summary"]
    verdict = payload.get("verdict", {})
    adaptive = payload.get("adaptive", {})
    thresholds = payload.get("thresholds", {})
    truth = payload.get("truth", [])
    lines = []
    lines.append("# Adaptive near/far area quadrature (issue #84, task 2)")
    lines.append("")
    lines.append("Generated by `tools/issue84/render_adaptive_acceptance_doc.py` from "
                 "`docs/issue84/adaptive_area_acceptance.json`.")
    lines.append("")
    lines.append("## 1. Declared before the run")
    lines.append("")
    lines.append("The acceptance thresholds are module constants "
                 "(`tools/issue84/adaptive_area_acceptance.py`, `THRESHOLDS`) so the "
                 "verdict cannot be chosen after the numbers are known:")
    lines.append("")
    lines.append(_table(["quantity", "threshold"], [
        ["a-posteriori gate, maximum over the point set", _fmt(thresholds.get("gate_max"))],
        ["a-posteriori gate, 90th percentile", _fmt(thresholds.get("gate_p90"))],
        ["estimator error against the saturated reference, maximum",
         _fmt(thresholds.get("true_max"))],
        ["median seconds per point relative to production fan 28:8",
         _fmt(thresholds.get("cost_ratio"), 2)],
    ]))
    lines.append("")
    lines.append("The estimator is a self-difference, not an error bound: it can only show "
                 "that the next refinement moved the value by less than the threshold. Section 5 "
                 "is the only place where the true error is measured.")
    lines.append("")
    lines.append("## 2. Construction")
    lines.append("")
    lines.append(_table(["ingredient", "choice"], [
        ["near set", "distance <= %s * circumradius, or distance <= core radius"
         % _fmt(adaptive.get("near_ratio"), 2)],
        ["near integrator", "projection fan %d:%d, refined at %d:%d"
         % (payload["production"]["order"], payload["production"]["strips"],
            payload["refinement"]["order"], payload["refinement"]["strips"])],
        ["far integrator", "composite Duffy, midpoint split to %d piece(s), order %d"
         % (4 ** int(adaptive.get("far_levels", 1)), int(adaptive.get("far_order", 8)))],
        ["estimator", "norm of (refined - base) area term per target"],
        ["per-face budget", "budget * share of |weight|, weight = |gamma|*area/2/max(d, core)^2"],
        ["budget", _fmt(adaptive.get("budget"))],
        ["escalation", "up to %s rounds; near order doubles (<= 96), far order +4 and one more "
                       "midpoint level per round" % adaptive.get("max_escalations")],
        ["gate reporting", "`quadrature_arguments()` raises, the field gates internally and "
                           "exposes the estimates through `pop_adaptive_estimates()`"],
    ]))
    lines.append("")
    lines.append("## 3. Point set")
    lines.append("")
    lines.append("Case `%s`, alpha %s deg, core radius %s, %d wall faces, wake faces %s, "
                 "%d field triangles." % (payload.get("case"),
                                          _fmt(payload.get("alpha_deg"), 2),
                                          _fmt(payload.get("core_radius")),
                                          payload["wall_faces"], payload.get("wake_faces"),
                                          payload.get("field_faces")))
    lines.append("")
    lines.append(_table(["set", "points", "gate median", "gate p90", "gate max",
                         "near fraction median", "median s/point"],
                        [[name,
                          block["count"],
                          _fmt(block["adaptive_quadrature_error"].get("median")),
                          _fmt(block["adaptive_quadrature_error"].get("p90")),
                          _fmt(block["adaptive_quadrature_error"].get("max")),
                          _fmt(block["near_fraction"].get("median")),
                          _fmt(block["seconds"].get("median"))]
                         for name, block in sorted(summary["per_set"].items())]))
    lines.append("")
    lines.append("## 4. Verdict")
    lines.append("")
    lines.append(_table(["quantity", "measured", "threshold", "pass"], [
        ["gate max", _fmt(verdict.get("gate_max", {}).get("value")),
         _fmt(verdict.get("gate_max", {}).get("limit")),
         _fmt(verdict.get("gate_max", {}).get("passed"))],
        ["gate p90", _fmt(verdict.get("gate_p90", {}).get("value")),
         _fmt(verdict.get("gate_p90", {}).get("limit")),
         _fmt(verdict.get("gate_p90", {}).get("passed"))],
        ["true error max", _fmt(verdict.get("true_max", {}).get("value")),
         _fmt(verdict.get("true_max", {}).get("limit")),
         _fmt(verdict.get("true_max", {}).get("passed"))],
        ["median s/point vs production", _fmt(verdict.get("cost_ratio", {}).get("value")),
         "reported", "n/a"],
        ["peak RSS (MB)", _fmt(verdict.get("peak_rss_mb"), 1), "reported", "n/a"],
    ]))
    lines.append("")
    failing = [r for r in payload["points"]
               if r["adaptive_quadrature_error"] > float(thresholds.get("gate_max") or 0.0)]
    if failing:
        lines.append("")
        lines.append("Targets above the declared gate maximum (%d of %d):"
                     % (len(failing), len(payload["points"])))
        lines.append("")
        lines.append(_table(["point", "set", "x", "y", "z", "scale", "gate",
                             "escalations", "s"],
                            [["%d" % r["index"], r["set"], _fmt(r["xyz"][0], 3),
                              _fmt(r["xyz"][1], 3), _fmt(r["xyz"][2], 3),
                              _fmt(r.get("scale"), 4),
                              "%.3e" % r["adaptive_quadrature_error"],
                              r["escalations"], _fmt(r["seconds"], 1)]
                             for r in sorted(failing,
                                             key=lambda r: -r["adaptive_quadrature_error"])]))
        places = {(round(r["xyz"][0], 6), round(r["xyz"][1], 6), round(r["xyz"][2], 6))
                  for r in failing}
        lines.append("")
        lines.append("The %d failing rows resolve to %d distinct target location(s); the "
                     "selectors overlap, so this is one physical target seen twice, not two "
                     "independent failures." % (len(failing), len(places)))
        lines.append("")
        lines.append("The failing target is a trailing-edge sliver (triangle scale 0.0185) on "
                     "the sheet more than three chords downstream. Two escalation rounds of the "
                     "near fan (28:8 -> 56:8 -> 96:8) are not enough there, and the per-face "
                     "budget is spent on the largest weight terms first, so the sliver keeps a "
                     "1.9e-3 residual. This is the declared-threshold failure: the adaptive "
                     "evaluator is faster and is accurate where the estimator is small, but it "
                     "has no mechanism that subdivides a degenerate near-singular triangle.")
    lines.append("")
    lines.append("Cost basis: both columns time one " + BT + "limits()" + BT + " call for the same point "
                 "through the same API, so the ratio is like for like. The production call "
                 "integrates every triangle with the fan at 28:8 plus the refined 48:8 sample, "
                 "while the adaptive call uses the fan only on the near set and composite Duffy "
                 "elsewhere. The 0.618 s/point quoted in "
                 + BT + "docs/issue84/velocity_profile_109.json" + BT +
                 " is the batched area-term kernel "
                 "over many triangles and is not the same measurement.")
    lines.append("")
    lines.append("Adaptive median %s s/point, production fan 28:8 median %s s/point on the same "
                 "stratified subset (%d points). Escalations over the whole set: median %s, max "
                 "%s." % (_fmt(verdict.get("adaptive_median_seconds")),
                          _fmt(verdict.get("production_median_seconds")),
                          payload.get("production_subset", {}).get("count", 0),
                          _fmt(summary.get("escalations", {}).get("median"), 1),
                          _fmt(summary.get("escalations", {}).get("max"), 1)))
    lines.append("")
    lines.append("## 5. Estimator against the saturated reference")
    lines.append("")
    if truth:
        lines.append("The reference is the fan at %d:%d, the configuration whose "
                     "self-convergence is recorded in "
                     "`docs/issue84/projection_fan_knee.json`." % (
                         payload["reference"]["order"], payload["reference"]["strips"]))
        lines.append("")
        lines.append(_table(["point", "set", "estimator", "true error", "ratio"],
                            [["%d" % row["index"], row["set"],
                              _fmt(row["adaptive_quadrature_error"]),
                              "%.3e" % row["true_error"],
                              "%.3e" % (row["true_error"]
                                        / max(row["adaptive_quadrature_error"], 1e-30))]
                             for row in truth]))
        lines.append("")
        lines.append("A ratio below one means the estimator over-estimated the error, which is "
                     "the safe direction; a ratio above one means the refinement stalled on a "
                     "feature the estimator cannot see, and that point must not be claimed "
                     "converged.")
    else:
        lines.append("No truth points were measured in this run.")
    lines.append("")
    lines.append("## 6. What this does not establish")
    lines.append("")
    lines.append("- The far-field composite Duffy kernel has no error bound; only the estimator "
                 "and the truth subset constrain it.")
    lines.append("- Escalation is per target and per call, so the cost is data dependent; the "
                 "reported seconds are not a worst case.")
    lines.append("- Nothing here changes the default evaluator: `analytic_edges` stays the "
                 "default and the adaptive mode is opt-in.")
    lines.append("- A pass on the gate does not authorize the G2 geometry update (task 4).")
    lines.append("")
    lines.append("## 7. Reproduce")
    lines.append("")
    lines.append(FENCE + "powershell")
    lines.append("$env:PYTHONPATH='<worktree>;<repo>/runs'")
    lines.append("$env:TMP=$env:TEMP=$env:TMPDIR=$env:DSH_TMP_ROOT='<repo>/runs/pipwork'")
    lines.append("& '<repo>/.conda_env/python.exe' -u -m tools.issue84.adaptive_area_acceptance " +
                 "--main-half-surface <repo>/runs/half_cad_wingbody_v1/surface.json --out " +
                 "docs/issue84/adaptive_area_acceptance.json")
    lines.append(FENCE)
    lines.append("")
    lines.append("Total wall time of the recorded run: %s s." % _fmt(
        payload.get("total_seconds"), 1))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path,
                        default=Path("docs/issue84/adaptive_area_acceptance.json"))
    parser.add_argument("--out", type=Path,
                        default=Path("docs/ISSUE84_ADAPTIVE_AREA.md"))
    args = parser.parse_args(argv)
    payload = json.loads(args.json.read_text(encoding="utf-8"))
    args.out.write_text(render(payload), encoding="utf-8")
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
